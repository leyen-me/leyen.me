export function AssetMark({
  sym,
  size = 32,
  className,
}: {
  sym: string;
  size?: number;
  className?: string;
}) {
  const crypto = CRYPTO_MARKS[sym];
  if (crypto) {
    return (
      <svg
        className={className}
        viewBox="0 0 32 32"
        width={size}
        height={size}
        aria-hidden="true"
        focusable="false"
      >
        {crypto}
      </svg>
    );
  }

  const currency = CURRENCY_MARKS[sym];
  if (currency) {
    return (
      <span
        className={className ? `${className} swp-flag` : "swp-flag"}
        style={{ width: size, height: size }}
        aria-hidden="true"
      >
        <svg viewBox="0 0 512 512" width={size} height={size} focusable="false">
          {currency}
        </svg>
      </span>
    );
  }

  return (
    <span
      className="swp-mono"
      style={{ width: size, height: size, fontSize: size * 0.45 }}
      aria-hidden="true"
    >
      {sym.slice(0, 1)}
    </span>
  );
}
